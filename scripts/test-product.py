#!/usr/bin/env python3
"""Integration checks against a running local stack. Deletes only this run's own fixtures."""
import concurrent.futures as futures
import json
import os
import sys
import subprocess
import urllib.error
import urllib.request
from pathlib import Path
from uuid import uuid4
from datetime import datetime,timezone
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from camera.client import Backend


def main():
    settings={}
    for line in Path('.env').read_text().splitlines():
        if '=' in line and not line.startswith('#'):
            key,value=line.split('=',1);settings[key]=value
    base=os.environ.get('QC_TEST_URL','http://127.0.0.1:8080')
    operator=Backend(base,settings['QC_OPERATOR_PASSWORD'],'operator');operator.login()
    camera=Backend(base,settings['QC_INGEST_PASSWORD']);camera.login()
    ids=[]
    line='integration-'+uuid4().hex[:12]
    def payload(**overrides):
        p=dict(eventId=str(uuid4()),lineCode=line,cameraId='test-pc',bottleFound=True,
               defects=[],confidence=.9,modelVersion='integration-test',source='MANUAL',
               capturedAt=datetime.now(timezone.utc).isoformat())
        p.update(overrides);ids.append(p['eventId']);return p
    def post(client,p):return client.call('/api/v1/inspections',json.dumps(p).encode())
    def status(expected,fn):
        try:fn()
        except urllib.error.HTTPError as error:assert error.code==expected,(error.code,error.read())
        else:raise AssertionError(f'Expected HTTP {expected}')
    try:
        status(401,lambda:urllib.request.urlopen(base+'/api/v1/records'))
        status(403,lambda:urllib.request.urlopen(urllib.request.Request(base+'/api/v1/inspections',data=b'{}',headers={'Content-Type':'application/json'})))
        status(400,lambda:post(operator,{'lineCode':'missing-fields'}))
        missing=payload(bottleFound=False);assert post(operator,missing)['overallResult']=='REVIEW'
        low=payload(confidence=.2);assert post(operator,low)['overallResult']=='REVIEW'
        failed=payload(defects=['underfill']);assert post(operator,failed)['overallResult']=='FAIL'
        passed=payload();saved=post(operator,passed);assert saved['overallResult']=='PASS'
        assert post(operator,passed)['id']==saved['id']
        status(409,lambda:post(operator,{**passed,'defects':['missing_cap']}))
        # Same native insert races on multiple independent authenticated sessions.
        concurrent=payload()
        def send(_):
            client=Backend(base,settings['QC_OPERATOR_PASSWORD'],'operator');client.login();return post(client,concurrent)['id']
        with futures.ThreadPoolExecutor(max_workers=4) as executor:
            assert len(set(executor.map(send,range(8))))==1
        status(403,lambda:post(camera,payload()))
        status(403,lambda:camera.call('/api/v1/overview'))
        camera_event=payload(source='CAMERA',defects=['missing_cap'])
        assert post(camera,camera_event)['overallResult']=='FAIL'
        manual=operator.call('/api/v1/overview?source=MANUAL&line='+line)
        assert int(manual['totals']['total'])==5,manual
        real=operator.call('/api/v1/overview?source=CAMERA&line='+line)
        assert int(real['totals']['total'])==1
        rows=operator.call('/api/v1/records?source=MANUAL&result=REVIEW&line='+line)
        assert rows['total']==2
        history=operator.call('/api/v1/inspections')
        assert len(history)<=100
        assert any(row['eventId']==passed['eventId'] for row in history)
        status(403,lambda:camera.call('/api/v1/inspections'))
        assert 'MANUAL' in operator.call('/api/v1/export?source=MANUAL&line='+line).decode()
        status(400,lambda:operator.call('/api/v1/records?size=1000'))
        status(400,lambda:operator.call('/api/v1/overview?hours=9999'))
        # Existing MQTT compatibility with the same validated, idempotent schema.
        mqtt=payload(source='CAMERA',defects=['loose_cap'])
        subprocess.run(['docker','compose','exec','-T','mosquitto','sh','-ec',
            'mosquitto_pub -h localhost -u "$MQTT_USERNAME" -P "$MQTT_PASSWORD" -t production/product-test/inspections -q 1 -s'],
            input=json.dumps(mqtt),text=True,check=True)
        import time
        for _ in range(20):
            found=operator.call('/api/v1/records?source=CAMERA&line='+line)
            if found['total']==2:break
            time.sleep(.25)
        assert found['total']==2,found
        assert operator.call('/api/v1/vision/status')['modelReady'] is False
        operator.call('/api/auth/logout',b'')
        status(401,lambda:operator.call('/api/auth/me'))
        print('PASS auth, CSRF, role separation, validation, REVIEW, PASS/FAIL, concurrent idempotency, conflict detection, source filters, CSV, pagination limits, MQTT persistence and logout')
    finally:
        # Exact UUIDs are generated by this test; existing records are never removed.
        sql="DELETE FROM bottle_inspections WHERE event_id IN ("+','.join("'"+v+"'::uuid" for v in ids)+");"
        subprocess.run(['docker','compose','exec','-T','postgres','sh','-ec',
            'psql -X -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB"'],input=sql,text=True,check=True,stdout=subprocess.DEVNULL)

if __name__=='__main__':main()
