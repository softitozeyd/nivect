CREATE TABLE production_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  active BOOLEAN UNIQUE,
  started_at TIMESTAMPTZ NOT NULL,
  ended_at TIMESTAMPTZ,
  total_count BIGINT NOT NULL DEFAULT 0,
  pass_count BIGINT NOT NULL DEFAULT 0,
  fail_count BIGINT NOT NULL DEFAULT 0,
  review_count BIGINT NOT NULL DEFAULT 0,
  last_event_id UUID,
  last_payload_hash VARCHAR(64),
  CONSTRAINT session_active_or_null CHECK (active IS NULL OR active = TRUE),
  CONSTRAINT session_counts_nonnegative CHECK (total_count >= 0 AND pass_count >= 0 AND fail_count >= 0 AND review_count >= 0),
  CONSTRAINT session_counts_match CHECK (total_count = pass_count + fail_count + review_count)
);
ALTER TABLE bottle_inspections ADD COLUMN production_session_id BIGINT REFERENCES production_sessions(id);
ALTER TABLE bottle_inspections ADD COLUMN product_number BIGINT;
CREATE UNIQUE INDEX inspection_session_product_unique ON bottle_inspections(production_session_id,product_number) WHERE production_session_id IS NOT NULL;
